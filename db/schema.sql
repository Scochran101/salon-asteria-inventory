-- One table per Sheet tab. id = the Sheet row number, so rows keep their order.
-- client_id: the idempotency key the reworked app sends on addProduct, addZone
-- and restock, so a retried write returns the row it already made.

CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL UNIQUE,
  category text NOT NULL DEFAULT '',
  brand text NOT NULL DEFAULT '',
  line text NOT NULL DEFAULT '',
  sub_type text NOT NULL DEFAULT '',
  shade text NOT NULL DEFAULT '',
  par double precision,
  price double precision,
  verify text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  active text NOT NULL DEFAULT '',
  client_id text UNIQUE
);

CREATE TABLE IF NOT EXISTS zones (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zone_id text NOT NULL UNIQUE,
  name text NOT NULL DEFAULT '',
  sort_order double precision,
  active text NOT NULL DEFAULT '',
  client_id text UNIQUE
);

CREATE TABLE IF NOT EXISTS zone_counts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id text NOT NULL,
  zone_id text NOT NULL,
  qty double precision,
  last_updated timestamptz,
  UNIQUE (product_id, zone_id)
);

CREATE TABLE IF NOT EXISTS snapshots (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id integer NOT NULL UNIQUE,
  date timestamptz,
  status text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS snapshot_lines (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id integer NOT NULL,
  product_id text NOT NULL,
  zone_id text NOT NULL,
  qty double precision
);
CREATE INDEX IF NOT EXISTS snapshot_lines_snapshot ON snapshot_lines (snapshot_id);

CREATE TABLE IF NOT EXISTS restocks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restock_id integer NOT NULL UNIQUE,
  date timestamptz,
  product_id text NOT NULL DEFAULT '',
  qty double precision,
  note text NOT NULL DEFAULT '',
  client_id text UNIQUE
);

-- Sign-in tokens. The Apps Script kept them in Script Properties ("tok_<uuid>").
CREATE TABLE IF NOT EXISTS sessions (
  token text PRIMARY KEY,
  expires_at timestamptz NOT NULL
);

-- One row per import: which file (sha256), which timezone, how many rows per table.
CREATE TABLE IF NOT EXISTS sheet_imports (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  imported_at timestamptz NOT NULL DEFAULT now(),
  source_file text NOT NULL,
  source_sha256 text NOT NULL,
  sheet_timezone text NOT NULL,
  row_counts jsonb NOT NULL
);

-- One row once Neon is the live database. The importer refuses to run while it
-- exists: loading the sheet would erase everything saved since the switch.
CREATE TABLE IF NOT EXISTS cutover (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  done_at timestamptz NOT NULL DEFAULT now(),
  note text NOT NULL DEFAULT ''
);

-- Wrong PINs/passwords per name ("name:first|last") and per address ("ip:..."),
-- for the wrong-attempt limit in api/index.js. The importer empties it.
CREATE TABLE IF NOT EXISTS login_failures (
  key text PRIMARY KEY,
  fails integer NOT NULL,
  first_at timestamptz NOT NULL,
  locked_until timestamptz
);

